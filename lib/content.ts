// THE BRAND'S VOICE IS NOT THE OWNER'S VOICE, and that is this agent's distinguishing problem.
// Every other role agent learns how its owner writes and that is the right answer. A blunt
// founder can run a warm, careful brand, so the intake in apolloclaw2 asks about brand voice
// separately from personal voice, and asks for the words the brand never uses, which is the half
// that actually prevents off-brand copy. The pages talk about the banned list rather than about
// "trained on your tone", because the banned list is the part that works.
//
// The second thing is honesty about channels. The intake asks which channel actually works and
// which is a chore, on purpose, so the agent does not spread effort evenly across channels that
// do not deserve it. Most marketing tooling assumes you want more of everything.
//
// The third is publishing authority. Community replies are the one thing on the list that is
// published the moment it is written, so they get their own rules at setup, and the copy names
// that rather than glossing it.

